/**
 * MENTORS: you do not need to change this file.
 *
 * Alliance.java  -  the two alliances.                                          ROLE: helper
 *
 * An "enum" is a fixed list of names. A variable of type Alliance can only ever be
 * Alliance.RED or Alliance.BLUE, so a typo like "RDE" is caught when the code is built,
 * not during a match. RED comes first because it is our default.
 *
 *   MatchInfo.alliance = Alliance.BLUE;
 *   if (MatchInfo.alliance == Alliance.RED) { ... }
 */
public enum Alliance {
    RED,
    BLUE
}
